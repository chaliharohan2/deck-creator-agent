"""Render a :class:`Deck` to PowerPoint (.pptx) with python-pptx (MIT).

Design choices:
* 16:9 slides, every slide uses a real title placeholder so titles show up in
  PowerPoint's outline view / accessibility tree.
* Charts and tables are *native* PowerPoint objects, so they stay editable.
* Long text is fitted with a size heuristic instead of relying on autofit,
  which python-pptx cannot compute and LibreOffice renders inconsistently.
"""

from __future__ import annotations

from pathlib import Path

from lxml import etree
from PIL import Image
from pptx import Presentation
from pptx.chart.data import CategoryChartData
from pptx.dml.color import RGBColor
from pptx.enum.chart import XL_CHART_TYPE, XL_LABEL_POSITION, XL_LEGEND_POSITION, XL_MARKER_STYLE
from pptx.enum.shapes import MSO_SHAPE
from pptx.enum.text import MSO_ANCHOR, MSO_AUTO_SIZE, PP_ALIGN
from pptx.oxml.ns import qn
from pptx.util import Emu, Inches, Pt

from deck_agent.deck.model import (
    BulletSlide,
    ChartSlide,
    Deck,
    ImageSlide,
    QuoteSlide,
    SectionSlide,
    SlideBase,
    TableSlide,
    TitleSlide,
    TwoColumnSlide,
    bullet_level,
)
from deck_agent.deck.text import fit_font_size, mix, number_format, parse_inline, plain, sources_line
from deck_agent.deck.themes import Theme, get_theme

SLIDE_W, SLIDE_H = 13.333, 7.5
MARGIN = 0.6
CONTENT_TOP = 1.72
CONTENT_BOTTOM = 6.62
CONTENT_W = SLIDE_W - 2 * MARGIN

LAYOUT_TITLE, LAYOUT_TITLE_ONLY, LAYOUT_BLANK = 0, 5, 6
NO_STYLE_TABLE = "{2D5ABB26-0587-4C30-8999-92F81FD0307C}"  # "No Style, No Grid"

_CHART_TYPES = {
    "column": XL_CHART_TYPE.COLUMN_CLUSTERED,
    "bar": XL_CHART_TYPE.BAR_CLUSTERED,
    "line": XL_CHART_TYPE.LINE_MARKERS,
    "pie": XL_CHART_TYPE.PIE,
    "doughnut": XL_CHART_TYPE.DOUGHNUT,
    "area": XL_CHART_TYPE.AREA,
    "stacked_column": XL_CHART_TYPE.COLUMN_STACKED,
    "stacked_bar": XL_CHART_TYPE.BAR_STACKED,
}


def _rgb(hex_color: str) -> RGBColor:
    return RGBColor.from_string(hex_color.upper())


class PptxRenderer:
    def __init__(self, deck: Deck, theme: Theme | None = None):
        self.deck = deck
        self.theme = theme or get_theme(deck.theme)
        self.prs = Presentation()
        self.prs.slide_width = Inches(SLIDE_W)
        self.prs.slide_height = Inches(SLIDE_H)

    # ------------------------------------------------------------------ public
    def render(self, path: str | Path) -> Path:
        path = Path(path)
        path.parent.mkdir(parents=True, exist_ok=True)
        total = len(self.deck.slides)
        for number, slide in enumerate(self.deck.slides, 1):
            handler = getattr(self, f"_render_{slide.kind}")
            pslide = handler(slide)
            if not isinstance(slide, (TitleSlide, SectionSlide)):
                self._footer(pslide, number, total)
            if not isinstance(slide, TitleSlide):
                self._sources(pslide, slide)
            self._notes(pslide, slide)
        props = self.prs.core_properties
        props.title = self.deck.title[:250]
        props.subject = self.deck.subtitle[:250]
        props.author = self.deck.author[:250] or "deck-creator-agent"
        props.comments = "Generated by deck-creator-agent"
        self.prs.save(path)
        return path

    # ------------------------------------------------------------------ primitives
    def _new_slide(self, layout: int = LAYOUT_TITLE_ONLY, background: str | None = None):
        slide = self.prs.slides.add_slide(self.prs.slide_layouts[layout])
        fill = slide.background.fill
        fill.solid()
        fill.fore_color.rgb = _rgb(background or self.theme.background)
        return slide

    def _runs(self, paragraph, text: str, *, size: float, color: str, font: str | None = None,
              bold: bool = False, italic: bool = False) -> None:
        for segment, is_bold in parse_inline(text):
            run = paragraph.add_run()
            run.text = segment
            f = run.font
            f.size = Pt(size)
            f.bold = bold or is_bold
            f.italic = italic
            f.color.rgb = _rgb(color)
            f.name = font or self.theme.body_font

    def _textbox(self, slide, x: float, y: float, w: float, h: float, *, anchor=MSO_ANCHOR.TOP, margin: float = 0.0):
        tb = slide.shapes.add_textbox(Inches(x), Inches(y), Inches(w), Inches(h))
        tf = tb.text_frame
        tf.word_wrap = True
        tf.auto_size = MSO_AUTO_SIZE.NONE
        tf.vertical_anchor = anchor
        for side in ("left", "right", "top", "bottom"):
            setattr(tf, f"margin_{side}", Inches(margin))
        return tb

    def _text(self, slide, text: str, x, y, w, h, *, size, color, bold=False, italic=False, font=None,
              align=PP_ALIGN.LEFT, anchor=MSO_ANCHOR.TOP):
        tb = self._textbox(slide, x, y, w, h, anchor=anchor)
        p = tb.text_frame.paragraphs[0]
        p.alignment = align
        self._runs(p, text, size=size, color=color, bold=bold, italic=italic, font=font)
        return tb

    def _set_title(self, slide, text: str, *, x=MARGIN, y=0.42, w=CONTENT_W, h=1.0, size=None,
                   color=None, align=PP_ALIGN.LEFT, anchor=MSO_ANCHOR.BOTTOM):
        shape = slide.shapes.title
        if shape is None:
            shape = self._textbox(slide, x, y, w, h)
        shape.left, shape.top, shape.width, shape.height = Inches(x), Inches(y), Inches(w), Inches(h)
        tf = shape.text_frame
        tf.clear()
        tf.word_wrap = True
        tf.auto_size = MSO_AUTO_SIZE.NONE
        tf.vertical_anchor = anchor
        tf.margin_left = tf.margin_right = Inches(0)
        tf.margin_top = tf.margin_bottom = Inches(0.02)
        if size is None:
            n = len(plain(text))
            size = 34 if n <= 42 else 30 if n <= 60 else 26 if n <= 80 else 22
        p = tf.paragraphs[0]
        p.alignment = align
        p.line_spacing = 0.95
        self._runs(p, text, size=size, color=color or self.theme.title, bold=True, font=self.theme.heading_font)
        return shape

    def _accent_bar(self, slide, x=MARGIN, y=1.5, w=0.9, h=0.07, color=None):
        bar = slide.shapes.add_shape(MSO_SHAPE.RECTANGLE, Inches(x), Inches(y), Inches(w), Inches(h))
        bar.fill.solid()
        bar.fill.fore_color.rgb = _rgb(color or self.theme.accent)
        bar.line.fill.background()
        bar.shadow.inherit = False
        return bar

    def _card(self, slide, x, y, w, h, color=None):
        card = slide.shapes.add_shape(MSO_SHAPE.ROUNDED_RECTANGLE, Inches(x), Inches(y), Inches(w), Inches(h))
        card.adjustments[0] = 0.04
        card.fill.solid()
        card.fill.fore_color.rgb = _rgb(color or self.theme.surface)
        card.line.fill.background()
        card.shadow.inherit = False
        return card

    def _set_bullet(self, paragraph, level: int) -> None:
        pPr = paragraph._p.get_or_add_pPr()
        pPr.set("marL", str(int(Inches(0.34 + 0.4 * level))))
        pPr.set("indent", str(-int(Inches(0.3))))
        for tag in ("a:buClr", "a:buSzPct", "a:buFont", "a:buChar", "a:buNone", "a:buAutoNum"):
            for el in pPr.findall(qn(tag)):
                pPr.remove(el)
        clr = etree.SubElement(pPr, qn("a:buClr"))
        etree.SubElement(clr, qn("a:srgbClr")).set("val", self.theme.accent)
        etree.SubElement(pPr, qn("a:buSzPct")).set("val", "100000")
        etree.SubElement(pPr, qn("a:buFont")).set("typeface", "Arial")
        etree.SubElement(pPr, qn("a:buChar")).set("char", "•" if level == 0 else "–")

    def _bullets(self, slide, items: list[str], x, y, w, h, *, max_size: int = 26, color=None):
        parsed = [bullet_level(i) for i in items]
        sizes = tuple(s for s in (26, 24, 22, 20, 18, 16, 14, 13, 12) if s <= max_size)
        size = fit_font_size(parsed, w, h, sizes=sizes)
        tb = self._textbox(slide, x, y, w, h)
        tf = tb.text_frame
        for i, (level, text) in enumerate(parsed):
            p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
            s = size if level == 0 else max(size - 4, 11)
            p.line_spacing = 1.08
            if i:
                p.space_before = Pt(round(s * 0.55) if level == 0 else round(s * 0.25))
            self._set_bullet(p, level)
            self._runs(p, text, size=s, color=color or self.theme.text)
        return tb

    # ------------------------------------------------------------------ chrome
    def _footer(self, slide, number: int, total: int) -> None:
        t = self.theme
        self._text(slide, self.deck.title, MARGIN, 7.0, 8.5, 0.3, size=10, color=t.muted)
        self._text(slide, f"{number} / {total}", SLIDE_W - MARGIN - 1.5, 7.0, 1.5, 0.3, size=10,
                   color=t.muted, align=PP_ALIGN.RIGHT)

    def _sources(self, slide, s: SlideBase) -> None:
        line = sources_line(s.sources)
        credit = getattr(s, "credit", "")
        if credit:
            line = f"Image: {credit}" + (f"   {line}" if line else "")
        if line:
            on_cover = isinstance(s, SectionSlide)
            color = mix(self.theme.cover_background, self.theme.cover_text, 0.6) if on_cover else self.theme.muted
            self._text(slide, line, MARGIN, 6.68, CONTENT_W, 0.3, size=10, color=color, italic=True)

    def _notes(self, pslide, s: SlideBase) -> None:
        parts = [s.notes.strip()] if s.notes.strip() else []
        if s.sources:
            parts.append("Sources:\n" + "\n".join(f"- {src}" for src in s.sources))
        if getattr(s, "credit", ""):
            parts.append(f"Image credit: {s.credit}")
        if parts:
            pslide.notes_slide.notes_text_frame.text = "\n\n".join(parts)

    # ------------------------------------------------------------------ slide types
    def _render_title(self, s: TitleSlide):
        t = self.theme
        slide = self._new_slide(LAYOUT_TITLE, background=t.cover_background)
        self._accent_bar(slide, x=MARGIN + 0.05, y=2.2, w=1.3, h=0.09)
        self._set_title(slide, s.title, x=MARGIN, y=2.45, w=CONTENT_W - 1.0, h=1.9,
                        size=48 if len(s.title) <= 40 else 40 if len(s.title) <= 70 else 34,
                        color=t.cover_text, anchor=MSO_ANCHOR.TOP)
        sub_ph = next((ph for ph in slide.placeholders if ph.placeholder_format.idx == 1), None)
        subtitle = s.subtitle or self.deck.subtitle
        if sub_ph is not None:
            if subtitle:
                sub_ph.left, sub_ph.top = Inches(MARGIN), Inches(4.45)
                sub_ph.width, sub_ph.height = Inches(CONTENT_W - 1.0), Inches(1.0)
                tf = sub_ph.text_frame
                tf.clear()
                tf.word_wrap = True
                tf.vertical_anchor = MSO_ANCHOR.TOP
                tf.margin_left = Inches(0)
                p = tf.paragraphs[0]
                p.alignment = PP_ALIGN.LEFT
                self._runs(p, subtitle, size=22, color=mix(t.cover_background, t.cover_text, 0.82))
            else:
                sub_ph._element.getparent().remove(sub_ph._element)
        meta = " · ".join(x for x in (s.author or self.deck.author, s.date or self.deck.date) if x)
        if meta:
            self._text(slide, meta, MARGIN, 6.4, CONTENT_W, 0.4, size=14,
                       color=mix(t.cover_background, t.cover_text, 0.6))
        return slide

    def _render_section(self, s: SectionSlide):
        t = self.theme
        slide = self._new_slide(background=t.cover_background)
        self._accent_bar(slide, x=MARGIN + 0.05, y=2.75, w=1.0, h=0.08)
        self._set_title(slide, s.title, x=MARGIN, y=2.95, w=CONTENT_W - 1.5, h=1.4, size=40,
                        color=t.cover_text, anchor=MSO_ANCHOR.TOP)
        if s.subtitle:
            self._text(slide, s.subtitle, MARGIN, 4.45, CONTENT_W - 1.5, 1.2, size=20,
                       color=mix(t.cover_background, t.cover_text, 0.78))
        return slide

    def _content_slide(self, title: str):
        slide = self._new_slide()
        self._set_title(slide, title)
        self._accent_bar(slide)
        return slide

    def _render_bullets(self, s: BulletSlide):
        slide = self._content_slide(s.title)
        self._bullets(slide, s.bullets, MARGIN + 0.05, CONTENT_TOP + 0.1, CONTENT_W - 0.6,
                      CONTENT_BOTTOM - CONTENT_TOP - 0.15)
        return slide

    def _render_two_column(self, s: TwoColumnSlide):
        t = self.theme
        slide = self._content_slide(s.title)
        gap = 0.4
        col_w = (CONTENT_W - gap) / 2
        top, height = CONTENT_TOP + 0.1, CONTENT_BOTTOM - CONTENT_TOP - 0.15
        for i, (heading, bullets) in enumerate(((s.left_heading, s.left_bullets), (s.right_heading, s.right_bullets))):
            x = MARGIN + i * (col_w + gap)
            self._card(slide, x, top, col_w, height)
            inner_top = top + 0.3
            if heading:
                self._text(slide, heading, x + 0.35, inner_top, col_w - 0.7, 0.55, size=22, bold=True,
                           color=t.accent if t.accent != t.surface else t.title, font=t.heading_font)
                inner_top += 0.7
            self._bullets(slide, bullets, x + 0.3, inner_top, col_w - 0.6, top + height - inner_top - 0.25,
                          max_size=22)
        return slide

    def _render_chart(self, s: ChartSlide):
        t = self.theme
        slide = self._content_slide(s.title)
        top, height = CONTENT_TOP + 0.05, CONTENT_BOTTOM - CONTENT_TOP - 0.1
        chart_w = CONTENT_W
        if s.bullets:
            chart_w = CONTENT_W * 0.62
            panel_x = MARGIN + chart_w + 0.35
            panel_w = CONTENT_W - chart_w - 0.35
            self._card(slide, panel_x, top, panel_w, height)
            self._text(slide, "Key takeaways", panel_x + 0.3, top + 0.25, panel_w - 0.6, 0.45, size=16,
                       bold=True, color=t.accent if t.accent != t.surface else t.title)
            self._bullets(slide, s.bullets, panel_x + 0.25, top + 0.85, panel_w - 0.5, height - 1.1, max_size=18)

        categories, series = list(s.categories), [(x.name, list(x.values)) for x in s.series]
        horizontal = s.chart_type in ("bar", "stacked_bar")
        if horizontal:  # PowerPoint draws bar categories bottom-up; flip so item 1 is on top
            categories.reverse()
            series = [(n, list(reversed(v))) for n, v in series]
        data = CategoryChartData()
        data.categories = categories
        for name, values in series:
            data.add_series(name, values)
        gframe = slide.shapes.add_chart(_CHART_TYPES[s.chart_type], Inches(MARGIN), Inches(top),
                                        Inches(chart_w), Inches(height), data)
        chart = gframe.chart
        self._style_chart(chart, s, horizontal)
        return slide

    def _style_chart(self, chart, s: ChartSlide, horizontal: bool) -> None:
        t = self.theme
        pie = s.chart_type in ("pie", "doughnut")
        multi = len(s.series) > 1
        chart.font.size = Pt(12)
        chart.font.name = t.body_font
        chart.font.color.rgb = _rgb(t.text)
        chart.has_title = False
        _no_fill(chart._chartSpace, after=qn("c:chart"))
        chart.has_legend = multi or pie
        if chart.has_legend:
            chart.legend.position = XL_LEGEND_POSITION.RIGHT if pie else XL_LEGEND_POSITION.BOTTOM
            chart.legend.include_in_layout = False
            chart.legend.font.size = Pt(13)
            chart.legend.font.color.rgb = _rgb(t.text)
        plot = chart.plots[0]
        all_values = [v for x in s.series for v in x.values]
        fmt, _ = number_format(all_values)
        if pie:
            plot.vary_by_categories = True
            for j, point in enumerate(plot.series[0].points):
                point.format.fill.solid()
                point.format.fill.fore_color.rgb = _rgb(t.palette[j % len(t.palette)])
                point.format.line.color.rgb = _rgb(t.background)
                point.format.line.width = Pt(1.5)
            plot.has_data_labels = True
            labels = plot.data_labels
            labels.show_percentage = True
            labels.show_value = False
            labels.show_category_name = False
            labels.number_format = "0%"
            labels.number_format_is_linked = False
            labels.font.size = Pt(14)
            labels.font.bold = True
            if s.chart_type == "pie":
                labels.position = XL_LABEL_POSITION.OUTSIDE_END
                labels.font.color.rgb = _rgb(t.text)
            else:
                labels.font.color.rgb = _rgb("FFFFFF")
            return

        line_like = s.chart_type == "line"
        for i, ser in enumerate(plot.series):
            color = _rgb(t.palette[i % len(t.palette)])
            if line_like:
                ser.format.line.color.rgb = color
                ser.format.line.width = Pt(2.75)
                ser.smooth = False
                ser.marker.style = XL_MARKER_STYLE.CIRCLE
                ser.marker.size = 7
                ser.marker.format.fill.solid()
                ser.marker.format.fill.fore_color.rgb = color
                ser.marker.format.line.color.rgb = color
            else:
                ser.format.fill.solid()
                ser.format.fill.fore_color.rgb = color
                ser.format.line.fill.background()
        if s.chart_type in ("column", "bar", "stacked_column", "stacked_bar"):
            plot.gap_width = 55 if not multi else 80
            if s.chart_type.startswith("stacked"):
                plot.overlap = 100
        if not multi and s.chart_type in ("column", "bar", "line") and len(s.categories) <= 12:
            plot.has_data_labels = True
            labels = plot.data_labels
            labels.number_format = fmt
            labels.number_format_is_linked = False
            labels.font.size = Pt(12)
            labels.font.color.rgb = _rgb(t.text)
            labels.position = XL_LABEL_POSITION.ABOVE if line_like else XL_LABEL_POSITION.OUTSIDE_END

        grid = mix(t.background, t.text, 0.15)
        va, ca = chart.value_axis, chart.category_axis
        if min(all_values) >= 0:
            va.minimum_scale = 0  # never truncate the baseline: it exaggerates differences
        axis_fmt = "#,##0" if max(abs(v) for v in all_values) >= 10 else fmt
        va.has_major_gridlines = True
        va.major_gridlines.format.line.color.rgb = _rgb(grid)
        va.major_gridlines.format.line.width = Pt(0.75)
        va.format.line.fill.background()
        va.tick_labels.font.size = Pt(12)
        va.tick_labels.font.color.rgb = _rgb(t.muted)
        va.tick_labels.number_format = axis_fmt
        va.tick_labels.number_format_is_linked = False
        ca.has_major_gridlines = False
        ca.format.line.color.rgb = _rgb(grid)
        ca.tick_labels.font.size = Pt(13 if len(s.categories) <= 8 else 11)
        ca.tick_labels.font.color.rgb = _rgb(t.text)
        for axis, title in ((va, s.y_axis_title), (ca, s.x_axis_title)):
            if title:
                axis.has_title = True
                tf = axis.axis_title.text_frame
                tf.text = title
                run = tf.paragraphs[0].runs[0]
                run.font.size = Pt(12)
                run.font.bold = False
                run.font.color.rgb = _rgb(t.muted)

    def _render_table(self, s: TableSlide):
        t = self.theme
        slide = self._content_slide(s.title)
        n_rows, n_cols = len(s.rows) + 1, len(s.headers)
        longest = max(len(c) for row in [s.headers, *s.rows] for c in row) if s.rows else 10
        size = 18 if n_rows <= 5 and n_cols <= 4 else 16 if n_rows <= 8 else 14 if n_rows <= 10 else 12
        if longest > 60 or n_cols >= 6:
            size = min(size, 13)
        elif longest > 35:
            size = min(size, 15)
        row_h = max(0.42, size * 2.1 / 72)
        avail = CONTENT_BOTTOM - CONTENT_TOP - 0.15
        height = min(avail, row_h * n_rows)
        gframe = slide.shapes.add_table(n_rows, n_cols, Inches(MARGIN), Inches(CONTENT_TOP + 0.1),
                                        Inches(CONTENT_W), Inches(height))
        table = gframe.table
        style_id = gframe._element.graphic.graphicData.tbl.tblPr.find(qn("a:tableStyleId"))
        if style_id is not None:
            style_id.text = NO_STYLE_TABLE
        table.first_row = True
        table.horz_banding = False
        # column widths proportional to content length (clamped)
        weights = []
        for c in range(n_cols):
            longest_c = max(len(row[c]) for row in [s.headers, *s.rows])
            weights.append(min(max(longest_c, 6), 40))
        total_w = sum(weights)
        for c, wgt in enumerate(weights):
            table.columns[c].width = Emu(int(Inches(CONTENT_W) * wgt / total_w))
        for r in range(n_rows):
            table.rows[r].height = Inches(row_h)
            for c in range(n_cols):
                cell = table.cell(r, c)
                header = r == 0
                text = s.headers[c] if header else s.rows[r - 1][c]
                cell.fill.solid()
                if header:
                    cell.fill.fore_color.rgb = _rgb(t.accent)
                else:
                    cell.fill.fore_color.rgb = _rgb(t.surface if r % 2 == 0 else t.background)
                cell.margin_left = cell.margin_right = Inches(0.12)
                cell.margin_top = cell.margin_bottom = Inches(0.05)
                cell.vertical_anchor = MSO_ANCHOR.MIDDLE
                tf = cell.text_frame
                tf.clear()
                tf.word_wrap = True
                p = tf.paragraphs[0]
                p.alignment = PP_ALIGN.RIGHT if (not header and _is_numeric(text)) else PP_ALIGN.LEFT
                self._runs(p, text, size=size, bold=header, color=t.accent_text if header else t.text)
        return slide

    def _render_image(self, s: ImageSlide):
        t = self.theme
        slide = self._content_slide(s.title)
        top, height = CONTENT_TOP + 0.1, CONTENT_BOTTOM - CONTENT_TOP - 0.15
        if s.bullets:
            text_w = CONTENT_W * 0.42
            self._bullets(slide, s.bullets, MARGIN + 0.05, top, text_w - 0.2, height, max_size=22)
            box_x, box_w = MARGIN + text_w + 0.3, CONTENT_W - text_w - 0.3
        else:
            box_x, box_w = MARGIN, CONTENT_W
        caption_h = 0.45 if s.caption else 0.0
        box_h = height - caption_h
        path = Path(s.image_path)
        if not path.exists():
            self._card(slide, box_x, top, box_w, box_h)
            self._text(slide, f"[missing image: {path.name}]", box_x, top + box_h / 2 - 0.2, box_w, 0.4,
                       size=14, color=t.muted, align=PP_ALIGN.CENTER)
            return slide
        with Image.open(path) as im:
            iw, ih = im.size
        scale = min(box_w / iw, box_h / ih)
        w, h = iw * scale, ih * scale
        x = box_x + (box_w - w) / 2
        y = top + (box_h - h) / 2
        pic = slide.shapes.add_picture(str(path), Inches(x), Inches(y), Inches(w), Inches(h))
        pic._element.nvPicPr.cNvPr.set("descr", s.caption or s.title)
        if s.caption:
            self._text(slide, s.caption, box_x, y + h + 0.08, box_w, 0.4, size=13, italic=True,
                       color=t.muted, align=PP_ALIGN.CENTER)
        return slide

    def _render_quote(self, s: QuoteSlide):
        t = self.theme
        slide = self._new_slide(LAYOUT_TITLE_ONLY)
        # Keep the title placeholder (for accessibility) but make it the attribution line.
        self._text(slide, "“", MARGIN + 0.2, 0.7, 2.0, 2.0, size=160, bold=True, color=t.accent,
                   font="Georgia")
        n = len(s.quote)
        size = 40 if n <= 80 else 34 if n <= 140 else 28 if n <= 220 else 24
        self._text(slide, s.quote, MARGIN + 1.2, 2.0, CONTENT_W - 2.2, 3.4, size=size, italic=True,
                   color=t.title, font=t.heading_font, anchor=MSO_ANCHOR.MIDDLE)
        self._set_title(slide, f"— {s.attribution}" if s.attribution else " ", x=MARGIN + 1.2, y=5.55,
                        w=CONTENT_W - 2.2, h=0.6, size=20, color=t.muted, anchor=MSO_ANCHOR.TOP)
        return slide


def _no_fill(parent, after: str) -> None:
    """Make a chart's background transparent so it sits on the slide colour."""
    for old in parent.findall(qn("c:spPr")):
        parent.remove(old)
    sp = etree.Element(qn("c:spPr"))
    etree.SubElement(sp, qn("a:noFill"))
    ln = etree.SubElement(sp, qn("a:ln"))
    etree.SubElement(ln, qn("a:noFill"))
    anchor = parent.find(after)
    if anchor is not None:
        anchor.addnext(sp)


def _is_numeric(text: str) -> bool:
    cleaned = text.replace(",", "").replace("%", "").replace("$", "").replace("€", "").replace("£", "").strip()
    if not cleaned:
        return False
    try:
        float(cleaned.lstrip("+-"))
        return True
    except ValueError:
        return False


